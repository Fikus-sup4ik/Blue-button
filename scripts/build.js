/* No dependency bundler: output stays compatible with older Lampa WebViews. */
var fs = require('fs');
var path = require('path');
var root = path.resolve(__dirname, '..');
var files = [
  'src/core.js', 'src/diagnostics.js', 'src/title-resolver.js', 'src/normalizer.js',
  'src/cache-manager.js', 'adapters/adapter-base.js', 'adapters/lampac.js',
  'src/search-manager.js', 'src/lampa-bridge.js', 'src/components/results.js',
  'src/settings.js', 'src/bootstrap.js'
];
var banner = '/* Blue-button v0.1.1 | generated by scripts/build.js | ES5 */\n';
var output = banner + files.map(function (file) {
  return '/* ' + file + ' */\n' + fs.readFileSync(path.join(root, file), 'utf8');
}).join('\n\n');
fs.writeFileSync(path.join(root, 'dist', 'blue-button.js'), output, 'utf8');
console.log('Built dist/blue-button.js (' + Buffer.byteLength(output, 'utf8') + ' bytes)');
